test('a like action rejects a session removed after the page was rendered', async ({ page, context }) => {
  await loginUser(page, 'reader', 'password123')
  await createBlog(page, 'Protected likes', 'Reader Author', 'https://example.com/like')
  await page.getByRole('link', { name: 'Protected likes', exact: true }).click()
  await context.clearCookies()
  await page.getByRole('button', { name: 'Like', exact: true }).click()
  await expect(page.getByRole('main').getByRole('alert')).toContainText('Log in')
  await page.reload()
  await expect(page.getByTestId('blog-detail')).toContainText('0 likes')
})

test('long content stays within a narrow viewport on list, detail and personal pages', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 })
  await loginUser(page, 'reader', 'password123')
  const title = 'A'.repeat(120)
  await createBlog(page, title, 'A long author name', `https://example.com/${'b'.repeat(120)}`)
  for (const path of ['/blogs', '/me', '/users/reader']) {
    await page.goto(path)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  }
  await page.goto('/blogs')
  await page.getByRole('link', { name: title, exact: true }).click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
